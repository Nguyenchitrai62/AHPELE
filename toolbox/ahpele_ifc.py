UNSET, DERIVED = object(), object()


def parse_args(s, i):
    """Parses '(' ... ')' starting at s[i] == '('. Returns (list, index after ')')."""
    assert s[i] == "("
    i += 1
    out = []
    while True:
        while s[i] in " \t\r\n":
            i += 1
        c = s[i]
        if c == ")":
            return out, i + 1
        if c == ",":
            i += 1
            continue
        if c == "'":
            j = i + 1
            buf = []
            while True:
                k = s.find("'", j)
                if k < 0:
                    raise ValueError(f"unterminated string at offset {i}")
                buf.append(s[j:k])
                if k + 1 < len(s) and s[k + 1] == "'":
                    buf.append("'")
                    j = k + 2
                    continue
                i = k + 1
                break
            out.append("".join(buf))
        elif c == "(":
            v, i = parse_args(s, i)
            out.append(v)
        elif c == "#":
            m = re.compile(r"#(\d+)").match(s, i)
            out.append(Ref(int(m.group(1))))
            i = m.end()
        elif c == "$":
            out.append(UNSET)
            i += 1
        elif c == "*":
            out.append(DERIVED)
            i += 1
        elif c == ".":
            m = re.compile(r"\.([A-Za-z0-9_]+)\.").match(s, i)
            if not m:
                raise ValueError(f"bad enumeration at offset {i}: {s[i:i+20]!r}")
            out.append(Enum(m.group(1)))
            i = m.end()
        elif c == '"':
            k = s.index('"', i + 1)
            out.append(s[i + 1:k])
            i = k + 1
        elif c.isalpha():
            m = re.compile(r"([A-Za-z0-9_]+)\s*").match(s, i)
            name = m.group(1).upper()
            i = m.end()
            v, i = parse_args(s, i)
            out.append(Typed(name, v))
        else:
            m = re.compile(r"[-+]?(\d+\.?\d*|\.\d+)([eE][-+]?\d+)?").match(s, i)
            if not m:
                raise ValueError(f"unexpected character {c!r} at offset {i}: {s[i:i+30]!r}")
            t = m.group(0)
            out.append(float(t) if ("." in t or "e" in t.lower()) else int(t))
            i = m.end()


def parse(text):
    head = text[:4000]
    if "ISO-10303-21" not in head:
        errors.append("file does not start with ISO-10303-21 (not a STEP file)")
    m = re.search(r"FILE_SCHEMA\s*\(\s*\(\s*'([^']+)'", head)
    schema = (m.group(1).upper() if m else "")
    if not m:
        errors.append("no FILE_SCHEMA in the header")
    d0 = text.find("DATA;")
    d1 = text.rfind("ENDSEC;")
    if d0 < 0 or d1 < d0:
        errors.append("no DATA; ... ENDSEC; section")
        return schema, {}
    data = text[d0 + 5:d1]
    ents = {}
    pos = 0
    pat = re.compile(r"\s*#(\d+)\s*=\s*([A-Za-z0-9_]+)\s*\(")
    while True:
        m = pat.match(data, pos)
        if not m:
            rest = data[pos:].strip()
            if rest:
                errors.append(f"cannot parse the DATA section near: {rest[:80]!r}")
            break
        eid, name = int(m.group(1)), m.group(2).upper()
        try:
            args, j = parse_args(data, m.end() - 1)
        except (ValueError, IndexError, AssertionError) as exc:
            errors.append(f"#{eid} {name}: {exc}")
            k = data.find(";\n", m.end())
            pos = k + 2 if k > 0 else len(data)
            continue
        k = data.find(";", j)
        if k < 0 or data[j:k].strip():
            errors.append(f"#{eid} {name}: expected ';' after the attribute list, found {data[j:j+30]!r}")
            pos = k + 1 if k > 0 else len(data)
        else:
            pos = k + 1
        if eid in ents:
            errors.append(f"#{eid} is defined twice")
        ents[eid] = (name, args)
    return schema, ents


def refs_in(v):
    if isinstance(v, Ref):
        yield int(v)
    elif isinstance(v, list):
        for x in v:
            yield from refs_in(x)
    elif isinstance(v, Typed):
        for x in v.args:
            yield from refs_in(x)


def val(v):
    if isinstance(v, Typed):
        return val(v.args[0]) if v.args else None
    if v is UNSET or v is DERIVED:
        return None
    return v


def check(path, verbose=False):
    text = open(path, encoding="utf-8", errors="replace").read()
    schema_name, ents = parse(text)
    key = ALIASES.get(schema_name, schema_name)
    sch = SCHEMAS.get(key)
    if sch is None:
        warnings.append(f"schema {schema_name!r} unknown here; attribute counts not checked")
    attrs = {}
    for eid, (name, args) in ents.items():
        for r in refs_in(args):
            if r not in ents:
                errors.append(f"#{eid} {name} refers to #{r}, which does not exist")
        if sch is None:
            continue
        spec = sch.get(name)
        if spec is None:
            errors.append(f"#{eid} {name}: not an entity of {key}")
            continue
        names = [a for a in spec if a != "!abstract"]
        if "!abstract" in spec:
            errors.append(f"#{eid} {name}: abstract entity, cannot be instantiated")
        if len(args) != len(names):
            errors.append(f"#{eid} {name}: {len(args)} attributes, {key} expects {len(names)}: ({', '.join(names)})")
        else:
            attrs[eid] = dict(zip(names, args))
    n = {}
    for name, _ in ents.values():
        n[name] = n.get(name, 0) + 1
    notes.append(f"{len(ents)} entities, schema {schema_name or '?'}; " + ", ".join(
        f"{k}: {n.get(k, 0)}" for k in ("IFCPROJECT", "IFCSITE", "IFCBUILDING", "IFCBUILDINGSTOREY", "IFCSPACE")))
    if n.get("IFCPROJECT", 0) != 1:
        errors.append(f"{n.get('IFCPROJECT', 0)} IfcProject entities (exactly 1 expected)")
    # units
    for eid, a in attrs.items():
        if ents[eid][0] == "IFCSIUNIT" and str(val(a.get("UnitType"))) == "LENGTHUNIT":
            notes.append(f"length unit: {val(a.get('Prefix')) or ''}{val(a.get('Name'))}")
    # decomposition and property sets
    children, psets_of = {}, {}
    for eid, a in attrs.items():
        nm = ents[eid][0]
        if nm in ("IFCRELAGGREGATES", "IFCRELCONTAINEDINSPATIALSTRUCTURE"):
            parent = a.get("RelatingObject", a.get("RelatingStructure"))
            kids = a.get("RelatedObjects", a.get("RelatedElements")) or []
            if isinstance(parent, Ref):
                children.setdefault(int(parent), []).extend(int(k) for k in kids if isinstance(k, Ref))
        if nm == "IFCRELDEFINESBYPROPERTIES":
            pdef = a.get("RelatingPropertyDefinition")
            for o in a.get("RelatedObjects") or []:
                if isinstance(o, Ref) and isinstance(pdef, Ref):
                    psets_of.setdefault(int(o), []).append(int(pdef))

    def pset_summary(oid):
        out = {}
        for p in psets_of.get(oid, []):
            pa = attrs.get(p)
            if not pa:
                continue
            props = {}
            for pr in pa.get("HasProperties") or []:
                q = attrs.get(int(pr)) if isinstance(pr, Ref) else None
                if q:
                    props[str(val(q.get("Name")))] = val(q.get("NominalValue"))
            out[str(val(pa.get("Name")))] = props
        return out

    parents = {k: p for p, ks in children.items() for k in ks}

    def polygon(profile_id):
        pa = attrs.get(profile_id)
        if not pa or ents[profile_id][0] != "IFCARBITRARYCLOSEDPROFILEDEF":
            return None
        curve = pa.get("OuterCurve")
        ca = attrs.get(int(curve)) if isinstance(curve, Ref) else None
        if not ca or ents[int(curve)][0] != "IFCPOLYLINE":
            return None
        pts = []
        for p in ca.get("Points") or []:
            c = attrs.get(int(p)) if isinstance(p, Ref) else None
            if c and isinstance(c.get("Coordinates"), list):
                pts.append(tuple(float(x) for x in c["Coordinates"][:2]))
        return pts

    def simple(pts):
        if len(pts) > 1 and pts[0] == pts[-1]:
            pts = pts[:-1]
        k = len(pts)
        def inter(p1, p2, p3, p4):
            def o(a, b, c):
                return (b[0]-a[0])*(c[1]-a[1]) - (b[1]-a[1])*(c[0]-a[0])
            d1, d2, d3, d4 = o(p3, p4, p1), o(p3, p4, p2), o(p1, p2, p3), o(p1, p2, p4)
            return ((d1 > 0) != (d2 > 0)) and ((d3 > 0) != (d4 > 0)) and 0 not in (d1, d2, d3, d4)
        for i in range(k):
            for j in range(i + 1, k):
                if abs(i - j) <= 1 or (i == 0 and j == k - 1):
                    continue
                if inter(pts[i], pts[(i+1) % k], pts[j], pts[(j+1) % k]):
                    return False
        return True

    def solids_of(oid):
        out = []
        a = attrs.get(oid, {})
        rep = a.get("Representation")
        ra = attrs.get(int(rep)) if isinstance(rep, Ref) else None
        for sr in (ra or {}).get("Representations") or []:
            sa = attrs.get(int(sr)) if isinstance(sr, Ref) else None
            if not sa:
                continue
            ident, rtype = val(sa.get("RepresentationIdentifier")), val(sa.get("RepresentationType"))
            if str(rtype).lower() == "boundingbox":
                warnings.append(f"#{oid}: has a BoundingBox representation")
            for it in sa.get("Items") or []:
                if isinstance(it, Ref) and ents.get(int(it), ("",))[0] == "IFCEXTRUDEDAREASOLID":
                    ea = attrs.get(int(it), {})
                    out.append((ident, rtype, int(it), ea))
        return out

    for eid, (name, _) in sorted(ents.items()):
        if name not in ("IFCSITE", "IFCBUILDING", "IFCBUILDINGSTOREY", "IFCSPACE", "IFCBUILDINGELEMENTPROXY") or eid not in attrs:
            continue
        a = attrs[eid]
        line = f"#{eid} {name} {val(a.get('Name'))!r}"
        if eid not in parents and name != "IFCSITE":
            warnings.append(f"#{eid} {name} {val(a.get('Name'))!r} is not aggregated/contained under any parent")
        if name == "IFCBUILDINGSTOREY":
            el = val(a.get("Elevation"))
            line += f" Elevation={el}"
            if el is None:
                warnings.append(f"#{eid} IfcBuildingStorey {val(a.get('Name'))!r} has no Elevation")
        kids = [k for k in children.get(eid, []) if ents.get(k, ("",))[0] == "IFCBUILDINGSTOREY"]
        if kids:
            els = [val(attrs.get(k, {}).get("Elevation")) for k in kids]
            line += f" storeys={len(kids)} elevations={els}"
            if len(set(els)) != len(els):
                warnings.append(f"#{eid}: duplicate storey elevations {els}")
        for ident, rtype, sid, ea in solids_of(eid):
            prof = ea.get("SweptArea")
            depth = val(ea.get("Depth"))
            pts = polygon(int(prof)) if isinstance(prof, Ref) else None
            if pts:
                ring = pts[:-1] if len(pts) > 1 and pts[0] == pts[-1] else pts
                area = abs(sum(ring[i][0]*ring[(i+1) % len(ring)][1] - ring[(i+1) % len(ring)][0]*ring[i][1]
                               for i in range(len(ring)))) / 2
                line += f" | {ident}/{rtype} extrusion #{sid}: {len(ring)}-point profile, area {area:.2f}, depth {depth}"
                if len(ring) < 3 or area <= 0:
                    errors.append(f"#{sid}: degenerate footprint polygon ({len(ring)} points, area {area})")
                elif not simple(pts):
                    errors.append(f"#{sid}: footprint polygon self-intersects")
                if pts[0] != pts[-1]:
                    notes.append(f"#{sid}: polyline is not closed explicitly (first point != last point)")
            else:
                line += f" | {ident}/{rtype} extrusion #{sid}, depth {depth}"
            if depth is None or (isinstance(depth, (int, float)) and depth <= 0):
                errors.append(f"#{sid}: extrusion depth must be > 0 (got {depth})")
        ps = pset_summary(eid)
        if ps:
            line += " | psets " + json.dumps(ps, default=str)[:600]
        notes.append(line)
    return errors, warnings, notes


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    rc = 0
    for path in [a for a in sys.argv[1:] if not a.startswith("--")]:
        errors.clear(); warnings.clear(); notes.clear()
        try:
            check(path)
        except Exception as exc:  # noqa: BLE001
            errors.append(f"checker crashed: {type(exc).__name__}: {exc}")
        print(f"== {path}: {len(errors)} error(s), {len(warnings)} warning(s)")
        for e in errors[:80]:
            print("ERROR  ", e)
        if len(errors) > 80:
            print(f"ERROR   ... and {len(errors) - 80} more")
        for w in warnings[:40]:
            print("WARN   ", w)
        for n in notes[:120]:
            print("       ", n)
        rc |= 1 if errors else 0
    return rc


if __name__ == "__main__":
    sys.exit(main())
